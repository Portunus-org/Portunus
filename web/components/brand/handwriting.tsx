"use client"

import * as React from "react"

import { handwritingPaths } from "@/lib/handwriting-paths"
import { cn } from "@/lib/utils"

// Pen speed in path units per second: every phrase is written at the same
// pace, so a short word finishes sooner than a long greeting.
const PEN_SPEED = 1100
// Pause while the pen is lifted between strokes.
const PEN_LIFT = 0.03

/**
 * A greeting written by hand: the ink of a script font is revealed through
 * a mask made of the pen's trajectory (the centre line of the letters, in
 * writing order), so each letter appears exactly where the pen passes.
 * Paths are generated by server/tools/handwriting.
 */
export function Handwriting({ text, className, onDone }: { text: string; className?: string; onDone?: () => void }) {
  const id = React.useId().replace(/:/g, "")
  const path = handwritingPaths[text]

  const timeline = React.useMemo(() => {
    if (!path) return { strokes: [], total: 0 }
    let t = 0
    const strokes = path.strokes.map((s) => {
      const duration = s.length / PEN_SPEED
      const delay = t
      t += duration + PEN_LIFT
      return { ...s, duration, delay }
    })
    return { strokes, total: t }
  }, [path])

  const onDoneRef = React.useRef(onDone)
  React.useEffect(() => {
    onDoneRef.current = onDone
  })
  React.useEffect(() => {
    const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches
    const timer = setTimeout(() => onDoneRef.current?.(), reduced ? 0 : timeline.total * 1000 + 250)
    return () => clearTimeout(timer)
  }, [timeline.total])

  if (!path) {
    // A phrase without generated paths: plain text rather than nothing.
    return <p className={cn("text-center text-4xl font-semibold", className)}>{text}</p>
  }

  const [x, y, w, h] = path.viewBox
  return (
    <svg viewBox={path.viewBox.join(" ")} className={cn("w-full", className)} role="img" aria-label={text}>
      <defs>
        {/* Bounds set explicitly: the default mask region would clip the
            parts of the letters above the baseline origin. */}
        <mask id={`${id}-pen`} maskUnits="userSpaceOnUse" x={x} y={y} width={w} height={h}>
          {timeline.strokes.map((s, i) => (
            <path
              key={i}
              d={s.d}
              fill="none"
              stroke="white"
              strokeWidth={path.pen}
              strokeLinecap="round"
              strokeLinejoin="round"
              className="animate-pen"
              style={{
                strokeDasharray: s.length + 1,
                strokeDashoffset: s.length + 1,
                animation: `pen-write ${s.duration}s linear ${s.delay}s forwards`,
              }}
            />
          ))}
        </mask>
      </defs>
      <path d={path.ink} fill="currentColor" mask={`url(#${id}-pen)`} />
    </svg>
  )
}
